# Runs once at startup: set motor power/speed and the starting heading.
def pre_autonomous():
   # actions to do when the program starts
   brain.screen.clear_screen()
   brain.screen.print("pre auton code")
   intake.set_max_torque(100, PERCENT)
   intake.set_velocity(100, PERCENT)
   output.set_max_torque(100, PERCENT)
   output.set_velocity(100, PERCENT)
   # Reset the inertial heading so later turns are measured from here.
   drivetrain.set_heading(90, DEGREES)
   drivetrain.set_drive_velocity(35, PERCENT)
   drivetrain.set_turn_velocity(25, PERCENT)
   print_thread = Thread(print_variable)


# Autonomous routine (runs when the field controller starts the autonomous period).
def autonomous():
   intake.spin(FORWARD)
   drivetrain.drive_for(FORWARD, 4, INCHES, wait=True)
   drivetrain.turn_for(RIGHT, 90, DEGREES)
   drivetrain.drive(REVERSE)
   wait(1, SECONDS)
   intake.spin(FORWARD)
   drivetrain.stop()
   #drivetrain.set_heading(0, DEGREES)
   drivetrain.drive(FORWARD)
   # Keep driving until the distance sensor reads at least 28 in (moving away from the wall).
   while dis.object_distance(INCHES) < 28:
       pass
   drivetrain.stop()
   intake.spin(FORWARD)
   wait(1, SECONDS)
   # Brief reverse pulse to un-jam blocks in the intake.
   intake.spin(REVERSE)
   wait(0.2, SECONDS)
   intake.spin(FORWARD)
   drivetrain.drive_for(FORWARD, 7, INCHES, wait=True)
   output.spin(REVERSE)
   wait(0.3, SECONDS)
   output.stop()
   # Brief reverse pulse to un-jam blocks in the intake.
   intake.spin(REVERSE)
   wait(0.2, SECONDS)
   intake.stop()
   intake.spin(FORWARD)
   wait(0.5, SECONDS)
   intake.stop()
   drivetrain.turn_for(LEFT, 130, DEGREES)
   drivetrain.drive(REVERSE)
   # Keep backing up until the distance sensor reads 13 in or less (closing in on the goal/wall).
   while dis.object_distance(INCHES) > 13:
       pass
   drivetrain.stop()
   output.spin(REVERSE)
   intake.spin(FORWARD)
   wait(3, SECONDS)
   output.spin(FORWARD)
   wait(0.3, SECONDS)
   output.spin(REVERSE)
   wait(3, SECONDS)
   output.spin(FORWARD)
   wait(0.3, SECONDS)
   output.spin(REVERSE)
   wait(3, SECONDS)
   output.stop()
   intake.stop()

