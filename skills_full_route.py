# Debug helper: prints distance-sensor reading and heading to the console every 100 ms.
def print_variable():
   while True:
       s = dis.object_distance(INCHES)
       d = drivetrain_inertial.heading(DEGREES)
       print(str(s) + "in " + str(math.floor(d)) + " *")
       wait(100, MSEC) # Small delay to allow other code to run




# Runs once at startup: set motor power/speed and the starting heading.
def pre_autonomous():
   # actions to do when the program starts
   brain.screen.clear_screen()
   brain.screen.print("pre auton code")
   intake.set_max_torque(100, PERCENT)
   intake.set_velocity(100, PERCENT)
   output.set_max_torque(100, PERCENT)
   output.set_velocity(100, PERCENT)
   # Reset the inertial heading so later turns are measured from here.
   drivetrain.set_heading(90, DEGREES)
   drivetrain.set_drive_velocity(50, PERCENT)
   drivetrain.set_turn_velocity(25, PERCENT)
   print_thread = Thread(print_variable)


