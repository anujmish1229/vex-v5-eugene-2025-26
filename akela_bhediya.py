# Debug helper: prints distance-sensor reading and heading to the console every 100 ms.
def print_variable():
   while True:
       s = dis.object_distance(INCHES)
       d = drivetrain_inertial.heading(DEGREES)
       print(str(s) + "in " + str(math.floor(d)) + " *")
       wait(100, MSEC) # Small delay to allow other code to run




# Runs once at startup: set motor power/speed and the starting heading.
def pre_autonomous():
   # actions to do when the program starts
   brain.screen.clear_screen()
   brain.screen.print("pre auton code")
   intake.set_max_torque(100, PERCENT)
   intake.set_velocity(100, PERCENT)
   output.set_max_torque(100, PERCENT)
   output.set_velocity(100, PERCENT)
   # Reset the inertial heading so later turns are measured from here.
   drivetrain.set_heading(90, DEGREES)
   drivetrain.set_drive_velocity(35, PERCENT)
   drivetrain.set_turn_velocity(25, PERCENT)
   print_thread = Thread(print_variable)


# Autonomous routine (runs when the field controller starts the autonomous period).
def autonomous():
   intake.spin(FORWARD)
   drivetrain.drive_for(FORWARD, 5, INCHES, wait=True)
   drivetrain.turn_for(LEFT, 90, DEGREES)
   drivetrain.drive(REVERSE)
   wait(1, SECONDS)
   intake.spin(FORWARD)
   drivetrain.stop()
   # Reset the inertial heading so later turns are measured from here.
   drivetrain.set_heading(0, DEGREES)
   drivetrain.drive(FORWARD)
   # Keep driving until the distance sensor reads at least 28 in (moving away from the wall).
   while dis.object_distance(INCHES) < 28:
       pass
   drivetrain.stop()
   intake.spin(FORWARD)
   wait(1.5, SECONDS)
   intake.spin(FORWARD)
   output.spin(REVERSE)
   wait(0.6, SECONDS)
   output.stop()
   # Brief reverse pulse to un-jam blocks in the intake.
   intake.spin(REVERSE)
   wait(0.4, SECONDS)
   intake.spin(FORWARD)
   drivetrain.drive_for(FORWARD, 15, INCHES, wait=True)
   intake.spin(FORWARD)
   output.spin(REVERSE)
   wait(0.2, SECONDS)
   output.stop()
   # Brief reverse pulse to un-jam blocks in the intake.
   intake.spin(REVERSE)
   wait(0.4, SECONDS)
   intake.spin(FORWARD)
   drivetrain.turn_for(LEFT, 90, DEGREES)
   drivetrain.drive_for(FORWARD, 32, INCHES, wait=True)
   drivetrain.stop()
   intake.spin(FORWARD)
   wait(1, SECONDS)
   # Brief reverse pulse to un-jam blocks in the intake.
   intake.spin(REVERSE)
   wait(0.4, SECONDS)
   intake.spin(FORWARD)
   wait(1, SECONDS)
   # Brief reverse pulse to un-jam blocks in the intake.
   intake.spin(REVERSE)
   wait(0.4, SECONDS)
   intake.spin(FORWARD)
   drivetrain.drive_for(FORWARD, 3, INCHES, wait=True)
   drivetrain.turn_for(LEFT, 40, DEGREES, wait=True)
   drivetrain.drive(REVERSE)
   # Keep backing up until the distance sensor reads 14 in or less (closing in on the goal/wall).
   while dis.object_distance(INCHES) > 14:
       pass
   drivetrain.stop()
   intake.spin(FORWARD)
   output.spin(REVERSE)
   wait(2, SECONDS)
   intake.spin(REVERSE)
   output.spin(FORWARD)
   wait(0.4, SECONDS)
   intake.spin(FORWARD)
   output.spin(REVERSE)
   wait(2, SECONDS)
   intake.spin(REVERSE)
   output.spin(FORWARD)
   wait(0.4, SECONDS)
   intake.spin(FORWARD)
   output.spin(REVERSE)
   wait(2, SECONDS)
   output.stop()
   intake.stop()
   drivetrain.drive_for(FORWARD, 50, INCHES, wait=True)
   drivetrain.turn_for(LEFT, 40, DEGREES, wait=True)
   drivetrain.drive(REVERSE)
   # Keep backing up until the distance sensor reads 6 in or less (closing in on the goal/wall).
   while dis.object_distance(INCHES) > 6:
       pass
   drivetrain.stop()
   output.spin(FORWARD)
   intake.spin(FORWARD)
   wait(3, SECONDS)
   output.spin(REVERSE)
   wait(0.3, SECONDS)
   output.spin(FORWARD)
   wait(3, SECONDS)
   output.spin(REVERSE)
   wait(0.3, SECONDS)
   output.spin(FORWARD)
   wait(3, SECONDS)
   output.stop()
   intake.stop()

# Driver control. Joystick driving is handled by the generated rc_auto_loop thread above,
# so this loop only keeps the program alive.
def user_control():
   print_thread = Thread(print_variable)
   drivetrain.set_turn_velocity(25, PERCENT)
   # place driver control in this while loop
   while True:
       wait(20, MSEC)


